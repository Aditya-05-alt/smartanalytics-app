-- Conner inventory: structure clone of the Hoot tables (no data, no cron, no triggers).
--   conner_config               <- smart_hoot_config
--   smart_conner_inventory      <- smart_hoot_inventory       (insert-only, one row per unit per pull day)
--   smart_conner_inventory_live <- smart_hoot_inventory_live  (insert-only, one row per unit per pull day)
-- Hoot upserts on sk; here sk is NOT unique so every day's pull is kept as new rows.

CREATE TABLE IF NOT EXISTS public.conner_config (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name        text,
  hoot_id              text,
  hoot_url             text NOT NULL,
  is_active            boolean DEFAULT true,
  created_at           timestamptz DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  ga4_customer_id      text,
  website_platform     text,
  dealer_category      text,
  show_all_dealers_vdp boolean NOT NULL DEFAULT false,
  show_all_dealers_all boolean NOT NULL DEFAULT false,
  show_all_dealers_srp boolean NOT NULL DEFAULT false,
  inv_type_raw_key     text,
  ga4_property_id      text
);

CREATE TABLE IF NOT EXISTS public.smart_conner_inventory (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sk               text NOT NULL,
  vin              text,
  url              text,
  advertiser       text,
  make             text,
  model            text,
  year             text,
  price            numeric,
  condition        text,
  first_seen       timestamptz DEFAULT now(),
  last_seen        timestamptz,
  raw_data         jsonb,
  customer_name    text,
  location         text,
  msrp             numeric,
  type_            text,
  trim             text,
  stock_number     text,
  website_platform text,
  update_date      date NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Kolkata')::date,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_smart_conner_inventory_update_date
  ON public.smart_conner_inventory (update_date DESC);
CREATE INDEX IF NOT EXISTS idx_smart_conner_inventory_customer_date
  ON public.smart_conner_inventory (customer_name, update_date DESC);
CREATE INDEX IF NOT EXISTS idx_smart_conner_inventory_sk_date
  ON public.smart_conner_inventory (sk, update_date DESC);

CREATE TABLE IF NOT EXISTS public.smart_conner_inventory_live (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sk               text NOT NULL,
  vin              text,
  url              text,
  advertiser       text,
  make             text,
  model            text,
  year             text,
  price            numeric,
  condition        text,
  raw_data         jsonb,
  customer_name    text,
  ga4_customer_id  text,
  location         text,
  msrp             numeric,
  type_            text,
  trim             text,
  stock_number     text,
  website_platform text,
  synced_at        timestamptz NOT NULL DEFAULT now(),
  update_date      date NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Kolkata')::date,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_conner_inv_live_update_date
  ON public.smart_conner_inventory_live (update_date DESC);
CREATE INDEX IF NOT EXISTS idx_conner_inv_live_customer_name
  ON public.smart_conner_inventory_live (customer_name, update_date DESC);
CREATE INDEX IF NOT EXISTS idx_conner_inv_live_ga4_customer_id
  ON public.smart_conner_inventory_live (ga4_customer_id, update_date DESC);
CREATE INDEX IF NOT EXISTS idx_conner_inv_live_sk_date
  ON public.smart_conner_inventory_live (sk, update_date DESC);
CREATE INDEX IF NOT EXISTS idx_conner_inv_live_synced_at
  ON public.smart_conner_inventory_live (synced_at DESC);

ALTER TABLE public.conner_config               ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smart_conner_inventory      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smart_conner_inventory_live ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS conner_config_select_authenticated ON public.conner_config;
CREATE POLICY conner_config_select_authenticated
  ON public.conner_config FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS smart_conner_inventory_select_authenticated ON public.smart_conner_inventory;
CREATE POLICY smart_conner_inventory_select_authenticated
  ON public.smart_conner_inventory FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS smart_conner_inventory_live_select_authenticated ON public.smart_conner_inventory_live;
CREATE POLICY smart_conner_inventory_live_select_authenticated
  ON public.smart_conner_inventory_live FOR SELECT TO authenticated USING (true);

-- Writes go through service_role only (loaders); the browser roles can read, never write.
REVOKE ALL ON public.conner_config, public.smart_conner_inventory, public.smart_conner_inventory_live
  FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.conner_config, public.smart_conner_inventory, public.smart_conner_inventory_live
  TO authenticated;
GRANT ALL ON public.conner_config, public.smart_conner_inventory, public.smart_conner_inventory_live
  TO service_role;
